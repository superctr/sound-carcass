static const uint8_t blank[7] = { 0 };

const uint8_t *lcd_font_glyph(uint8_t code)
{
	if (code >= 0x20 && code < 0x80)
		return ascii[code - 0x20];
	if (code >= 0x80)
		return upper[code - 0x80];
	if (code >= 0x10)
		return low[code - 0x10];
	return blank;   /* 0x00-0x0f are the user-defined characters, the caller's to look up */
}
